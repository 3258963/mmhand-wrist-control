"""Analytic two-axis cable wrist. Standard library only; SI units/radians.

Input model_parameters.json is generated by build_geometry_handoff.py.
This models fixed-center polylines, not sliding rim contact or elasticity.
"""
import json
import math
from pathlib import Path


def add(a, b): return [x+y for x, y in zip(a, b)]
def sub(a, b): return [x-y for x, y in zip(a, b)]
def scale(a, s): return [x*s for x in a]
def dot(a, b): return sum(x*y for x, y in zip(a, b))
def cross(a, b):
    return [a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0]]
def norm(a): return math.sqrt(dot(a, a))


def rotate(v, axis, angle):
    c, s = math.cos(angle), math.sin(angle)
    return add(add(scale(v, c), scale(cross(axis, v), s)), scale(axis, dot(axis, v)*(1-c)))


def around(p, axis, origin, angle):
    return add(origin, rotate(sub(p, origin), axis, angle))


def segment_coefficients(a, b, origin, axis):
    """Squared length from fixed a to rotated b = A+B*cos(q)+C*sin(q)."""
    u, v = sub(a, origin), sub(b, origin)
    return [dot(u,u)+dot(v,v)-2*dot(axis,u)*dot(axis,v),
            -2*(dot(u,v)-dot(axis,u)*dot(axis,v)),
            -2*dot(u,cross(axis,v))]


def length_arm(abc, angle):
    A, B, C = abc
    c, s = math.cos(angle), math.sin(angle)
    squared = A+B*c+C*s
    if squared <= 1e-24:
        raise ValueError('Degenerate cable segment: length derivative undefined')
    length = math.sqrt(squared)
    return length, (B*s-C*c)/(2*length)


class WristGeometry:
    def __init__(self, parameters):
        self.p = parameters

    @classmethod
    def load(cls, path=None):
        path = Path(path) if path else Path(__file__).with_name('model_parameters.json')
        return cls(json.loads(path.read_text(encoding='utf-8')))

    def evaluate(self, roll_rad, pitch_rad):
        """Return modeled P1..P8 lengths (m), R (m), and all 24 world points (m)."""
        if not all(math.isfinite(v) for v in [roll_rad, pitch_rad]):
            raise ValueError('Angles must be finite radians')
        ar, ap = self.p['axes']['roll'], self.p['axes']['pitch_zero']
        xyz = []
        for point in self.p['points']:
            v = point['zero_world_m']
            if point['body'] == 'palm':
                v = around(v, ap['direction_world'], ap['origin_world_m'], pitch_rad)
            if point['body'] != 'base':
                v = around(v, ar['direction_world'], ar['origin_world_m'], roll_rad)
            xyz.append(v)
        lengths, rr, rp = [], [], []
        for cable in self.p['cables']:
            sr, r = length_arm(cable['roll_ABC_m2'], roll_rad)
            sp, p = length_arm(cable['pitch_ABC_m2'], pitch_rad)
            lengths.append(cable['constant_length_m']+sr+sp)
            rr.append(r); rp.append(p)
        return {'lengths_m':lengths, 'R_m':[rr,rp], 'points_world_m':xyz}

    def evaluate_degrees(self, roll_deg, pitch_deg):
        return self.evaluate(math.radians(roll_deg), math.radians(pitch_deg))

    def geometric_jacobian(self, roll_rad, pitch_rad):
        """Independent vector chain-rule route; includes both endpoints of all segments."""
        result = self.evaluate(roll_rad,pitch_rad)
        ar, ap0 = self.p['axes']['roll'], self.p['axes']['pitch_zero']
        ap = rotate(ap0['direction_world'],ar['direction_world'],roll_rad)
        op = around(ap0['origin_world_m'],ar['direction_world'],ar['origin_world_m'],roll_rad)
        derivatives = []
        for marker, point in zip(self.p['points'],result['points_world_m']):
            dr = cross(ar['direction_world'],sub(point,ar['origin_world_m'])) if marker['body']!='base' else [0.,0.,0.]
            dp = cross(ap,sub(point,op)) if marker['body']=='palm' else [0.,0.,0.]
            derivatives.append([dr,dp])
        R = [[0.]*3 for _ in range(2)]
        for cable in range(3):
            for k in range(7):
                i=cable*8+k
                d=sub(result['points_world_m'][i+1],result['points_world_m'][i])
                u=scale(d,1/norm(d))
                for j in range(2):
                    R[j][cable]-=dot(u,sub(derivatives[i+1][j],derivatives[i][j]))
        return R


if __name__=='__main__':
    import argparse
